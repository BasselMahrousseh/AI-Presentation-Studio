-- ============================================
-- AI Presentation Studio Database Schema
-- ============================================

-- ============================================
-- AIPS_PROJECT
-- ============================================

CREATE TABLE AIPS_PROJECT (
    PROJECT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    OWNER_ID VARCHAR2(100) NOT NULL,
    TEAM_ID VARCHAR2(100),
    TITLE VARCHAR2(255) NOT NULL,
    CLASSIFICATION VARCHAR2(50),
    STATUS VARCHAR2(50),
);

-- ============================================
-- AIPS_SOURCE_DOC
-- ============================================

CREATE TABLE AIPS_SOURCE_DOC (
    SOURCE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROJECT_ID NUMBER NOT NULL,
    OBJECT_URI VARCHAR2(500) NOT NULL,
    SHA256 VARCHAR2(64) NOT NULL,
    MIME_TYPE VARCHAR2(100),
    SCAN_STATUS VARCHAR2(50),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_SOURCE_PROJECT
        FOREIGN KEY (PROJECT_ID)
        REFERENCES AIPS_PROJECT(PROJECT_ID)
);

-- ============================================
-- AIPS_SOURCE_CHUNK
-- ============================================

CREATE TABLE AIPS_SOURCE_CHUNK (
    CHUNK_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SOURCE_ID NUMBER NOT NULL,
    PAGE_NO NUMBER,
    SECTION_PATH VARCHAR2(500),
    TEXT CLOB,
    VECTOR CLOB,

    CONSTRAINT FK_CHUNK_SOURCE
        FOREIGN KEY (SOURCE_ID)
        REFERENCES AIPS_SOURCE_DOC(SOURCE_ID)
);

-- ============================================
-- AIPS_TEMPLATE
-- ============================================

CREATE TABLE AIPS_TEMPLATE (
    TEMPLATE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(255) NOT NULL,
    OWNER_TEAM VARCHAR2(100),
    STATUS VARCHAR2(50),
    CURRENT_VERSION_ID NUMBER,
);

-- ============================================
-- AIPS_TEMPLATE_VERSION
-- ============================================

CREATE TABLE AIPS_TEMPLATE_VERSION (
    TEMPLATE_VERSION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    TEMPLATE_ID NUMBER NOT NULL,
    MANIFEST_JSON CLOB,
    PACKAGE_URI VARCHAR2(500),
    COMPATIBILITY VARCHAR2(255),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_TEMPLATE_VERSION
        FOREIGN KEY (TEMPLATE_ID)
        REFERENCES AIPS_TEMPLATE(TEMPLATE_ID)
);

-- ============================================
-- AIPS_DECK
-- ============================================

CREATE TABLE AIPS_DECK (
    DECK_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROJECT_ID NUMBER NOT NULL,
    CURRENT_VERSION_ID NUMBER,
    TEMPLATE_ID NUMBER,

    CONSTRAINT FK_DECK_PROJECT
        FOREIGN KEY (PROJECT_ID)
        REFERENCES AIPS_PROJECT(PROJECT_ID),

    CONSTRAINT FK_DECK_TEMPLATE
        FOREIGN KEY (TEMPLATE_ID)
        REFERENCES AIPS_TEMPLATE(TEMPLATE_ID)
);

-- ============================================
-- AIPS_DECK_VERSION
-- ============================================

CREATE TABLE AIPS_DECK_VERSION (
    VERSION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    DECK_ID NUMBER NOT NULL,
    PARENT_VERSION_ID NUMBER,
    STATUS VARCHAR2(50),
    PPTX_URI VARCHAR2(500),
    PDF_URI VARCHAR2(500),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_VERSION_DECK
        FOREIGN KEY (DECK_ID)
        REFERENCES AIPS_DECK(DECK_ID),

    CONSTRAINT FK_PARENT_VERSION
        FOREIGN KEY (PARENT_VERSION_ID)
        REFERENCES AIPS_DECK_VERSION(VERSION_ID)
);

-- ============================================
-- AIPS_SLIDE_VERSION
-- ============================================

CREATE TABLE AIPS_SLIDE_VERSION (
    SLIDE_VERSION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    VERSION_ID NUMBER NOT NULL,
    SLIDE_NO NUMBER NOT NULL,
    SLIDE_SPEC_JSON CLOB,
    RENDER_URI VARCHAR2(500),
    QA_SCORE NUMBER(5,2),

    CONSTRAINT FK_SLIDE_VERSION
        FOREIGN KEY (VERSION_ID)
        REFERENCES AIPS_DECK_VERSION(VERSION_ID)
);

-- ============================================
-- AIPS_ASSET
-- ============================================

CREATE TABLE AIPS_ASSET (
    ASSET_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROJECT_ID NUMBER NOT NULL,
    TYPE VARCHAR2(100),
    OBJECT_URI VARCHAR2(500),
    LICENSE_METADATA_JSON CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_ASSET_PROJECT
        FOREIGN KEY (PROJECT_ID)
        REFERENCES AIPS_PROJECT(PROJECT_ID)
);

-- ============================================
-- AIPS_JOB
-- ============================================

CREATE TABLE AIPS_JOB (
    JOB_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROJECT_ID NUMBER NOT NULL,
    TYPE VARCHAR2(100),
    STATUS VARCHAR2(50),
    CURRENT_STAGE VARCHAR2(100),
    PROGRESS NUMBER(5,2),

    CONSTRAINT FK_JOB_PROJECT
        FOREIGN KEY (PROJECT_ID)
        REFERENCES AIPS_PROJECT(PROJECT_ID)
);

CREATE TABLE AIPS_MODEL_RUN (
    MODEL_RUN_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    JOB_ID NUMBER NOT NULL,

    MODEL_NAME VARCHAR2(100),

    PROVIDER VARCHAR2(100),

    PROMPT_TOKENS NUMBER,

    COMPLETION_TOKENS NUMBER,

    TOTAL_TOKENS NUMBER,

    LATENCY_MS NUMBER,

    STATUS VARCHAR2(50),

    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_MODEL_RUN
        FOREIGN KEY (JOB_ID)
        REFERENCES AIPS_JOB(JOB_ID)
);

CREATE TABLE AIPS_QA_RESULT (
    QA_RESULT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    SLIDE_VERSION_ID NUMBER NOT NULL,

    SCORE NUMBER(5,2),

    STATUS VARCHAR2(50),

    FEEDBACK CLOB,

    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_QA_SLIDE
        FOREIGN KEY (SLIDE_VERSION_ID)
        REFERENCES AIPS_SLIDE_VERSION(SLIDE_VERSION_ID)
);
